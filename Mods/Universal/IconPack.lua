				local value=info[2]
				if type(value)=='table' then
					for i,image in ipairs(value) do
						local imageLabel=Instance.new('ImageLabel') imageLabel.Visible=(i==1) imageLabel.Name=tostring(i) imageLabel.Size=UDim2.new(1,0,1,0) imageLabel.Position=UDim2.new(0,0,0,0) imageLabel.BackgroundTransparency=1 imageLabel.Image=image imageLabel.Parent=sg
						local id=tonumber(image:match("%d+") or "") if id then local idKey=tostring(id) if idsParts[idKey]==nil then idsParts[idKey]={} end table.insert(idsParts[idKey],p) end table.insert(assets,imageLabel)
					end
				else
					local image=value
					local imageLabel=Instance.new('ImageLabel') imageLabel.Size=UDim2.new(1,0,1,0) imageLabel.Position=UDim2.new(0,0,0,0) imageLabel.BackgroundTransparency=1 imageLabel.Image=image imageLabel.Parent=sg
					local id=tonumber(image:match("%d+") or "") if id then local idKey=tostring(id) if idsParts[idKey]==nil then idsParts[idKey]={} end table.insert(idsParts[idKey],p) end table.insert(assets,imageLabel)
				end
				ici=ici+1
			end
			rwi=(rwi+1)%10 
			if rwi==0 then task.wait(0.1) end
		end
		cli=(cli+1)%10 
		if cli==0 then task.wait(0.1) end
	end
	local primaryPart=Instance.new('Part') primaryPart.Name='PrimaryPart' primaryPart.Anchored=true primaryPart.CanCollide=false primaryPart.Transparency=1 primaryPart.Locked=true primaryPart.Size=Vector3.new(groupSizeX,size.Y,groupSizeZ) primaryPart.CanCollide=false primaryPart.CanTouch=false primaryPart.EnableFluidForces=false 
	local centerX=currentOffsetX+(groupSizeX/2)-(size.X/2)
	local centerZ=origin.Z+(groupSizeZ/2)-(size.Z/2)
	primaryPart.Position=Vector3.new(centerX,origin.Y,centerZ)
	primaryPart.Parent=group
	group.PrimaryPart=primaryPart
	table.insert(partLockeds,primaryPart)
	currentOffsetX=currentOffsetX+groupSizeX+gapBetweenGroups
end
